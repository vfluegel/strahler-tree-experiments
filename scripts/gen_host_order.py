#!/usr/bin/env python3
"""Generate exact host sizes, compressed size orders, and their short analysis."""

import argparse
from collections import defaultdict
import csv
import hashlib
import io
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def ratio_order(k_max, t_max):
    """The native bounded integer-ratio heap, including its tie behavior."""
    heap, seen, result = [], set(), []

    def ratio(pair):
        return max(pair) // min(pair)

    def push(pair):
        if pair in seen:
            return
        seen.add(pair)
        hole = len(heap)
        heap.append(pair)
        while hole:
            parent = (hole - 1) // 2
            if ratio(heap[parent]) <= ratio(pair):
                break
            heap[hole] = heap[parent]
            hole = parent
        heap[hole] = pair

    push((1, 1))
    while heap:
        pair, last = heap[0], heap.pop()
        if heap:
            hole = 0
            while 2 * hole + 1 < len(heap):
                child = 2 * hole + 1
                if child + 1 < len(heap) and ratio(heap[child + 1]) <= ratio(heap[child]):
                    child += 1
                heap[hole] = heap[child]
                hole = child
            while hole:
                parent = (hole - 1) // 2
                if ratio(heap[parent]) <= ratio(last):
                    break
                heap[hole] = heap[parent]
                hole = parent
            heap[hole] = last
        result.append(pair)
        k, t = pair
        if k < k_max:
            push((k + 1, t))
        if t < t_max:
            push((k, t + 1))
    return result


def monotone_prefix(order, k_max, t_max):
    """Greedy nested prefix, generated once for each table and cap."""
    result = [(1, 0)]
    for k, t in order:
        if k > k_max or t > t_max or k == 1 or t == 0:
            continue
        old_k, old_t = result[-1]
        if old_k == 1 or (k == old_k and t > old_t) or (k > old_k and t >= old_t + old_k - 1):
            result.append((k, t))
    return result


def inversion_counts(order, leaves):
    unequal = inverted = 0
    for i, left in enumerate(order):
        for right in order[i + 1:]:
            unequal += leaves[left] != leaves[right]
            inverted += leaves[left] > leaves[right]
    return dict(inversions=inverted, unequal_pairs=unequal,
                inversion_percent=round(100 * inverted / unequal, 2) if unequal else 0)


def build(genstree):
    command = [str(genstree), '--count-table', '--strahler=6', '--log-leaves=6', '--height=1000']
    raw = subprocess.check_output(command, text=True)
    groups = defaultdict(dict)
    for row in csv.DictReader(io.StringIO(raw)):
        h, k, t, leaves = (int(row[key]) for key in ('h', 'k', 't', 'leaves'))
        groups[h][k, t] = leaves
    assert set(groups) == set(range(1, 1001))
    orders = {h: sorted(values, key=lambda pair: (values[pair], *pair))
              for h, values in groups.items()}
    bands = [(h, order) for h, order in orders.items() if order != orders.get(h - 1)]
    csv_output = io.StringIO(newline='')
    writer = csv.writer(csv_output, lineterminator='\n')
    writer.writerow(('h', 'rank', 'k', 't', 'leaves'))
    for h, order in orders.items():
        for rank, (k, t) in enumerate(order, 1):
            writer.writerow((h, rank, k, t, groups[h][k, t]))
    prefixes, prefix_ids, variants = [], {}, []
    for h, order in bands:
        ids = []
        for k_cap in range(1, 7):
            row = []
            for t_cap in range(7):
                prefix = monotone_prefix(order, k_cap, t_cap)
                assert len(prefix) <= 7
                packed = sum((k * 8 + t) << (6 * i) for i, (k, t) in enumerate(prefix))
                if packed not in prefix_ids:
                    prefix_ids[packed] = len(prefixes)
                    prefixes.append(packed)
                row.append(prefix_ids[packed])
            ids.append(row)
        variants.append(ids)
    header = ['/* Generated by scripts/gen_host_order.py; see HOST-ORDER.md. */',
              '// clang-format off', '#ifndef HOST_ORDER_DATA_H', '#define HOST_ORDER_DATA_H 1',
              '#include <stdint.h>',
              'enum { HOST_ORDER_MAX_HEIGHT = 1000, HOST_ORDER_MAX_K = 6,',
              '       HOST_ORDER_MAX_T = 6, HOST_ORDER_PAIRS = 42 };',
              'typedef struct {', '  uint16_t height;', '  uint8_t count;',
              '  uint8_t pairs[HOST_ORDER_PAIRS]; /* k<<3 | t */',
              '  uint16_t monotone[6][7]; /* prefix ID by capped k-1 and t */',
              '} HostOrderBand;',
              '/* Packed six-bit pair codes, starting with the chain. */',
              'static uint64_t const host_monotone_prefixes[] = {']
    header += [f'  UINT64_C({prefix}),' for prefix in prefixes]
    header += ['};', 'static HostOrderBand const host_order_bands[] = {']
    for (h, order), ids in zip(bands, variants):
        codes = ', '.join(str(k * 8 + t) for k, t in order)
        header.append(f'  {{{h}, {len(order)}, {{{codes}}}, {{')
        header += ['    {' + ', '.join(map(str, row)) + '},' for row in ids]
        header.append('  }},')
    header += ['};', '// clang-format on', '#endif', '']
    summary = dict(rows=sum(map(len, groups.values())),
                   maximum=max(value for values in groups.values() for value in values.values()),
                   order_change_heights=[h for h, _ in bands],
                   monotone_prefixes=len(prefixes),
                   csv_sha256=hashlib.sha256(csv_output.getvalue().encode()).hexdigest(),
                   source_sha256=hashlib.sha256((ROOT / 'src/stree.c').read_bytes()).hexdigest(),
                   comparisons={})
    for h in (6, 10, 100, 1000):
        values = {pair: n for pair, n in groups[h].items() if pair[1] > 0}
        summary['comparisons'][h] = dict(
            ratio=inversion_counts(ratio_order(min(6, h), 6), values),
            lexicographic=inversion_counts(sorted(values), values))
    return csv_output.getvalue(), '\n'.join(header), summary


def analysis(summary):
    rows = '\n'.join(
        f"| {h} | {values['ratio']['inversion_percent']:.1f}% | "
        f"{values['lexicographic']['inversion_percent']:.1f}% |"
        for h, values in summary['comparisons'].items())
    changes = summary['order_change_heights']
    return f'''# Trying smaller hosts first

We counted the leaves of every Strahler host with **k=1…6, t=0…6 and
h=1…1000**, keeping the valid cases k≤h. That gives {summary['rows']:,} exact
counts in [sizes.csv](experimental/host-order/sizes.csv). The count comes from
the same U/V recurrence as `genstree`, without constructing the trees. The
largest has {summary['maximum']:,} leaves, so the old capped 32-bit count would
lose distinctions that matter here.

The idea is straightforward: at each height, try the hosts in increasing leaf
count, breaking ties by k and then t. Lexicographic search spends its time
allowance on t before reconsidering k. Ratio search balances the two numbers,
but cannot see that the same pair can describe a much larger tree at another
height. The table knows those sizes.

Here is one way to compare the orders: among pairs of hosts with different
sizes, how often does the search put the larger one first? Lower is better
for this particular objective; size order itself scores zero. This comparison
uses t≥1 for all methods, since the existing ratio search excludes t=0, and
reproduces its bounded heap's tie-breaking.

| Height h | Ratio: larger first | Lexicographic: larger first |
| ---: | ---: | ---: |
{rows}

At large heights, lexicographic order is already close to size order; ratio
still puts the larger host first in almost half of comparable pairs. The
benefit of a table is knowing the order at each height, rather than guessing
from the parameter values.

Height changes the answer. There are **{len(changes)} distinct consecutive
orders**, with the last change at **h={changes[-1]}**. Stopping at 100 would
miss {sum(h > 100 for h in changes)} later changes. Up to 1000, most adjacent
heights share exactly the same order, so the code stores only the boundaries
where an order changes. This is a small lookup, even though the CSV covers the
whole range.

This is an order by host size, not a predicted speedup. AD builds these trees;
STRPM represents them implicitly and benefits from its SIMD kernel. Graph
structure, lifting and verification still decide the running time. Nor does a
larger leaf count mean one host contains another: changing k can remove useful
branching shapes, as the [checked counterexample](docs/incremental-t.md)
shows. Leaf count alone gives no solve guarantee.

`--search=table` uses this bounded order, then continues in ratio order when
larger parameters are needed. Heights beyond 1000 also use the ratio fallback.
Both players follow one order selected from their larger initial height;
their own height bounds remain intact. The order stays fixed while shaving
shrinks the game. We keep the zero-budget pairs as well, including one-vertex
games. The existing ratio and lexicographic modes remain available for direct
comparisons.

`--search=monotone-tab` reads a precomputed nested prefix. Offline generation
starts from the chain and keeps a larger host when the [embedding bound](docs/host-monotonicity.md)
proves inclusion: keep k and raise t, or raise k with T≥t+k−1. The table stores
variants for each parameter cap, sharing {summary['monotone_prefixes']} distinct prefixes.
Runtime only looks up and reads the selected prefix. Both table modes then
continue with the ordinary ratio traversal, skipping pairs already tried.
The inclusion guarantee applies to the monotone prefix; ratio remains the
usual unrestricted fallback.

Regenerate with `python3 scripts/gen_host_order.py build/genstree`; add `--check`
to check the saved CSV, analysis and native table against the generator.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('genstree', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data, header, summary = build(args.genstree.resolve())
    outputs = {'experimental/host-order/sizes.csv': data,
               'src/host_order_data.h': header,
               'experimental/host-order/summary.json': json.dumps(summary, indent=2) + '\n',
               'HOST-ORDER.md': analysis(summary)}
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Stale generated file: {name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
